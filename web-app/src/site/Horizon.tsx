import { useEffect, useRef, useState } from 'react';
import { project, smoothPath } from '../sim/geometry';
import { trail } from '../sim/data';

/**
 * The path's length in the space the dash pattern is measured in.
 *
 * `vector-effect: non-scaling-stroke` makes the browser stroke the path *after*
 * the viewBox transform, and it measures the dash there too — but
 * getTotalLength() reports user units. This SVG is stretched with
 * preserveAspectRatio="none" across the full viewport, so above roughly 1000px
 * the two diverge by 40% or more: a dash cut to getTotalLength() leaves the
 * right-hand third of the trail sitting inside a gap once the reveal finishes,
 * and visible before it starts. Sampling the path through its screen CTM gives
 * the number the dash is actually working in.
 *
 * Verified in Chrome at 1420px: getTotalLength() 1059, painted length 1514.
 */
function paintedLength(path: SVGPathElement): number {
  const total = path.getTotalLength();
  const ctm = path.getScreenCTM();
  if (!ctm || !total) return total;
  // Far finer than the ~9-unit spacing between the trail's points, so no corner
  // is cut badly enough to matter.
  const steps = 1200;
  let sum = 0;
  let prev = path.getPointAtLength(0).matrixTransform(ctm);
  for (let i = 1; i <= steps; i++) {
    const point = path.getPointAtLength((i / steps) * total).matrixTransform(ctm);
    sum += Math.hypot(point.x - prev.x, point.y - prev.y);
    prev = point;
  }
  // Round up. Sampling can only undershoot, and undershooting ends the reveal
  // with a sliver missing; a pixel of extra travel across 1200ms reads as nothing.
  return Math.ceil(sum) + 1;
}

/**
 * The page's one signature element.
 *
 * A single net-worth trail runs the full width of the viewport as a slate
 * hairline, generated by the *same* code that draws the chart inside the device
 * screens — src/sim/geometry.ts — from the *same* series in src/sim/data.ts. The
 * devices sit on top of it, and inside their glass the identical curve is drawn
 * in the app's green. Outside: a hairline. Inside: the product.
 *
 * On load it draws once, left to right, and then never moves again. Under
 * prefers-reduced-motion it is simply already drawn.
 */
export function Horizon({ height = 260 }: { height?: number }) {
  const ref = useRef<SVGPathElement>(null);
  const [length, setLength] = useState(0);
  const [drawn, setDrawn] = useState(false);

  const values = trail('ALL').map((point) => point.value);
  const points = project(values, 1000, height, 0.18);
  const d = smoothPath(points);

  useEffect(() => {
    const path = ref.current;
    if (!path) return;
    const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if (reduced) {
      setDrawn(true);
      return;
    }
    setLength(paintedLength(path));
    // Two frames: one to commit the dash offset, one to start the transition.
    let inner = 0;
    const outer = requestAnimationFrame(() => {
      inner = requestAnimationFrame(() => setDrawn(true));
    });
    return () => {
      cancelAnimationFrame(outer);
      cancelAnimationFrame(inner);
    };
  }, []);

  return (
    <svg
      aria-hidden="true"
      viewBox={`0 0 1000 ${height}`}
      preserveAspectRatio="none"
      style={{ position: 'absolute', inset: 0, width: '100%', height: '100%', pointerEvents: 'none' }}
    >
      <path
        ref={ref}
        d={d}
        fill="none"
        stroke="var(--rule)"
        strokeWidth={1}
        strokeLinecap="round"
        // The app strokes the same series with lineCap/lineJoin .round
        // (DashboardView.swift:254). The joins are real now that the series is
        // interpolated linearly rather than splined.
        strokeLinejoin="round"
        vectorEffect="non-scaling-stroke"
        // The measured dash is only correct for the size measured at mount, so
        // retire it the moment it has served its purpose; a later resize then
        // cannot push the end of the trail back into a gap.
        onTransitionEnd={() => setLength(0)}
        style={
          length && !drawn
            ? { strokeDasharray: length, strokeDashoffset: length }
            : length
              ? {
                  strokeDasharray: length,
                  strokeDashoffset: 0,
                  transition: 'stroke-dashoffset 1200ms cubic-bezier(0.22, 1, 0.36, 1)',
                }
              : undefined
        }
      />
    </svg>
  );
}
